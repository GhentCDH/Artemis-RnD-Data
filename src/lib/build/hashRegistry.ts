import { readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { layerHashesPath } from "../paths";
import { ensureDir, fileExists } from "../utils/files";

/**
 * Committed, per-layer change-detection state: `build/Layers/<id>/hashes.txt`, a
 * plaintext `<sha256>  <source>` registry pairing each build input (an IIIF
 * canvas URL, a raw input path, or an `@build-param`) with a content hash of its
 * data. Because it lives under `build/` it is deployed/committed with the
 * outputs, so a fresh CI runner (or clone) can skip unchanged work with no warm
 * local cache — and the git diff of this file is exactly what changed.
 *
 * `.build-cache/` is now purely a local *accelerator* (warped GeoTIFFs, fetched
 * JSON) and is never required for a correct skip decision.
 *
 * Entries are grouped by category, each owned by the stage that produces it. A
 * flush replaces the entries of every category the build touched (dropping any
 * that disappeared upstream) and preserves categories a partial build did not
 * run, so a standalone `toponyms` build never clobbers the iiif hashes.
 */

export type HashCategory = "canvas" | "raster" | "toponyms" | "parcels";

/** Derive an entry's owning category from its source key. */
function categoryOf(source: string): HashCategory {
  if (source === "@raster") return "raster";
  if (source === "@toponyms" || source.includes("/toponyms/")) return "toponyms";
  if (source === "@parcels" || source.includes("/parcels/")) return "parcels";
  return "canvas"; // IIIF canvas URLs
}

const HEADER = [
  "# Source data-hash registry — committed change-detection state for the build.",
  "# Format: <sha256>  <source>   (IIIF canvas URL, raw input path, or @build-param).",
  "# Regenerated by the build; do not edit by hand. The diff is exactly what changed.",
];

export function buildForceEnabled(): boolean {
  return /^(1|true|yes)$/i.test(process.env.BUILD_FORCE ?? "");
}

export class LayerHashes {
  private readonly prev = new Map<string, string>();
  private readonly next = new Map<string, string>();
  private readonly touched = new Set<HashCategory>();

  private constructor(private readonly path: string) {}

  static async load(layerId: string): Promise<LayerHashes> {
    const instance = new LayerHashes(layerHashesPath(layerId));
    if (await fileExists(instance.path)) {
      for (const line of (await readFile(instance.path, "utf-8")).split("\n")) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith("#")) continue;
        const gap = trimmed.indexOf(" ");
        if (gap < 0) continue;
        const hash = trimmed.slice(0, gap).trim();
        const source = trimmed.slice(gap).trim();
        if (hash && source) instance.prev.set(source, hash);
      }
    }
    return instance;
  }

  /** Previously-committed hash for a source, if any (for per-item change reporting). */
  prevHash(source: string): string | undefined {
    return this.prev.get(source);
  }

  /** Whether the committed registry already had any entry for a category. */
  hasCategory(category: HashCategory): boolean {
    for (const source of this.prev.keys()) if (categoryOf(source) === category) return true;
    return false;
  }

  /**
   * Records this build's entries for a category and reports whether they are
   * identical to what was committed (same keys, same hashes). Always records, so
   * a subsequent flush is complete even when the caller decides to rebuild.
   */
  categoryUnchanged(category: HashCategory, entries: Iterable<[string, string]>): boolean {
    this.touched.add(category);
    const current = new Map(entries);
    for (const [source, hash] of current) this.next.set(source, hash);
    let prevCount = 0;
    for (const source of this.prev.keys()) if (categoryOf(source) === category) prevCount++;
    if (prevCount !== current.size) return false;
    for (const [source, hash] of current) if (this.prev.get(source) !== hash) return false;
    return true;
  }

  /** Merge untouched categories from the committed file with this run's entries and write. */
  async flush(): Promise<void> {
    const final = new Map<string, string>();
    for (const [source, hash] of this.prev) {
      if (!this.touched.has(categoryOf(source))) final.set(source, hash);
    }
    for (const [source, hash] of this.next) final.set(source, hash);
    if (final.size === 0) return;
    const body = [...final.entries()]
      .sort((a, b) => a[0].localeCompare(b[0]))
      .map(([source, hash]) => `${hash}  ${source}`)
      .join("\n");
    await ensureDir(dirname(this.path));
    await writeFile(this.path, `${HEADER.join("\n")}\n${body}\n`, "utf-8");
  }
}

export class HashRegistry {
  private readonly layers = new Map<string, LayerHashes>();

  constructor(readonly force = buildForceEnabled()) {}

  /** The layer's registry, loaded from its committed hashes.txt (cached per build). */
  async layer(layerId: string): Promise<LayerHashes> {
    let hashes = this.layers.get(layerId);
    if (!hashes) {
      hashes = await LayerHashes.load(layerId);
      this.layers.set(layerId, hashes);
    }
    return hashes;
  }

  /** Write every touched layer's hashes.txt. Call once at the end of a build. */
  async flushAll(): Promise<void> {
    for (const hashes of this.layers.values()) await hashes.flush();
  }
}
